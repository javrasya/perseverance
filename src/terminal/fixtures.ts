import { hasRustBehindIt } from "../snapshot/snapshot";
import type { RunReadout } from "./runs";

/**
 * What `dev:web` boots a rack of runs from: hand-written readouts, checked in,
 * with no PTY and no Rust process anywhere behind them.
 *
 * They exist because the states worth looking at are the ones a browser cannot
 * be talked into. Spec #28 names it exactly — *you cannot conjure a wedged AFK
 * run to check its still-state* — and neither can a Tauri window on demand: a
 * wedged reading wants five minutes of a research run saying nothing, and an
 * `awaitingOperator` one wants a CLI that stopped on a trust prompt, which is a
 * machine state rather than a click.
 *
 * **They are not the snapshot fixtures, and the difference is their whole
 * weakness.** `src/snapshot/fixtures.ts` holds files *generated by the model
 * crate*, and the Rust build fails if a checked-in one has stopped matching —
 * so a snapshot fixture is the model's own output or it is nothing. A run
 * readout is not part of `Snapshot`, no generator emits one, and the only thing
 * standing between this file and fiction is the `RunReadout` annotation below
 * plus the two tests that pin the wire shape from either side. Adding a key in
 * Rust will not fail this file; renaming one will fail `tsc`, and that is the
 * line being relied on.
 *
 * Nothing here ever presents itself as a live read. The seeding below is on the
 * no-Rust branch only, for the same reason no snapshot fixture is stamped
 * `github`: a browser quietly showing fiction as an observation is the one
 * failure the provenance rules exist to prevent.
 */

/**
 * Everything a readout carries that these fixtures are not making a point
 * about. Typed as `RunReadout` so a key added on the Rust side and mirrored
 * into the interface fails the build here rather than being silently absent
 * from every fixture.
 */
const ORDINARY: RunReadout = {
  run: 0,
  held: 0,
  dropped: 0,
  through: 0,
  end: 0,
  truncated: false,
  desynced: false,
  over: false,
  code: null,
  monitored: false,
  ending: "live",
  ticket: null,
  folder: null,
  silence: { kind: "nothing" },
  signal: null,
};

function a(readout: Partial<RunReadout> & Pick<RunReadout, "run">): RunReadout {
  return { ...ORDINARY, ...readout };
}

