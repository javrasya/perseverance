/**
 * The sets, each named for the reading it is there to put on screen.
 *
 * `none` is the default and is empty, so that a `dev:web` tab opened without
 * asking for runs is the tab this app has always opened: nothing bound, and
 * *Nothing is running here yet.* still a state somebody can look at.
 *
 * `the-rack` is every reading at once and every signal at once, which is the
 * only place the four silences can be compared rather than remembered.
 */
export const RUN_FIXTURES = {
  none: [],
  quiet: [QUIET_HOUR],
  "awaiting-operator": [AWAITING_OPERATOR],
  unwatched: [UNWATCHED],
  spent: [SPENT],
  ended: [ENDED],
  "the-rack": [
    a({ ...AWAITING_OPERATOR, monitored: true }),
    a({ ...QUIET_HOUR, monitored: false }),
    a({ ...UNWATCHED, monitored: false }),
    a({ ...SPENT, monitored: false }),
    a({ ...ENDED, monitored: false }),
    IDLING,
  ],
} satisfies Record<string, RunReadout[]>;

export type RunFixtureName = keyof typeof RUN_FIXTURES;

export const RUN_FIXTURE_NAMES = Object.keys(RUN_FIXTURES) as RunFixtureName[];

export const DEFAULT_RUN_FIXTURE: RunFixtureName = "none";

/** A copy each time, so a caller editing one cannot edit the fixture itself. */
export function runFixtureNamed(name: RunFixtureName): RunReadout[] {
  return structuredClone(RUN_FIXTURES[name]) as RunReadout[];
}

/**
 * Which set of runs a `dev:web` URL asked for.
 *
 * `?runs=` beside `?map=` and `?env=`, spelled once here: the parameter names
 * the thing being stood in for and the value names the state. An unknown name
 * falls back to the default rather than throwing, for the same reason a typo in
 * `?map=` does not blank the window.
 */
export const RUNS_PARAMETER = "runs";

export function requestedRunFixture(search?: string): RunFixtureName {
  const from = search ?? (typeof window === "undefined" ? "" : window.location.search);
  const asked = new URLSearchParams(from).get(RUNS_PARAMETER);
  return isRunFixtureName(asked) ? asked : DEFAULT_RUN_FIXTURE;
}

export function isRunFixtureName(name: string | null): name is RunFixtureName {
  return name !== null && name in RUN_FIXTURES;
}

/**
 * Which of a fixture set's runs the pane opens on, and `null` whenever there is
 * a harness behind the window.
 *
 * Without this the fixtures are unreachable: nothing in a browser spawns a run,
 * so nothing ever calls `monitor`, and the pane goes on saying *Nothing is
 * running here yet.* over a set of readouts it was handed. With Rust behind it
 * this answers `null` and the pane stays where every other surface put it — a
 * readout's own `monitored` flag is the harness's account of what it is
 * streaming, and letting it drive this window's selection would make arriving
 * at a run something the app did rather than something an operator pressed.
 */
export function fixtureRunToOpenOn(readouts: readonly RunReadout[]): number | null {
  if (hasRustBehindIt()) return null;
  return (readouts.find((readout) => readout.monitored) ?? readouts[0])?.run ?? null;
}
